-- 1) Identidad verificada del paciente.
--
-- El autorregistro es publico: cualquiera puede escribir cualquier DNI. Si el DNI fuera unico entre TODAS
-- las cuentas, el primero en registrarse con el DNI de otra persona se quedaria con el, y lo que la clinica
-- reserve despues "por DNI" para esa persona terminaria en la cuenta equivocada. Por eso el DNI solo es
-- unico entre los pacientes cuya identidad la clinica verifico en persona.
ALTER TABLE paciente ADD COLUMN identidad_verificada BOOLEAN NOT NULL DEFAULT FALSE;

-- Los pacientes que ya existian se dieron de alta antes de este control: se consideran verificados.
UPDATE paciente SET identidad_verificada = TRUE;

ALTER TABLE paciente DROP CONSTRAINT paciente_dni_key;
CREATE UNIQUE INDEX ux_paciente_dni_verificado ON paciente (dni) WHERE identidad_verificada;
CREATE INDEX ix_paciente_dni ON paciente (dni);

-- 2) Auditoria de accesos a historias clinicas ajenas (medicos y admins).
-- Solo se agrega; nada en la aplicacion modifica ni borra estas filas.
CREATE TABLE acceso_historial (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT    NOT NULL REFERENCES usuario (id),
    paciente_id BIGINT    NOT NULL REFERENCES paciente (id),
    accedido_en TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX ix_acceso_historial_paciente ON acceso_historial (paciente_id, accedido_en DESC);
CREATE INDEX ix_acceso_historial_usuario ON acceso_historial (usuario_id, accedido_en DESC);

-- Fase 2: atencion clinica (ver docs/modelo-datos.md, regla 7 y 8).
-- La Consulta es 1:1 con el turno y solo existe para turnos confirmados;
-- crearla pasa el turno a ATENDIDO (eso lo valida el servicio, no la base).
CREATE TABLE consulta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id   BIGINT NOT NULL UNIQUE REFERENCES turno (id),
    notas      TEXT,
    creada_en  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE diagnostico (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id   BIGINT       NOT NULL REFERENCES consulta (id),
    descripcion   VARCHAR(255) NOT NULL,
    codigo_cie10  VARCHAR(10)
);
CREATE INDEX ix_diagnostico_consulta ON diagnostico (consulta_id);

CREATE TABLE medicamento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(150) NOT NULL,
    presentacion  VARCHAR(100)
);
CREATE UNIQUE INDEX ux_medicamento_nombre ON medicamento (lower(nombre));

CREATE TABLE receta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id    BIGINT NOT NULL REFERENCES consulta (id),
    observaciones  VARCHAR(500),
    emitida_en     TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX ix_receta_consulta ON receta (consulta_id);

CREATE TABLE item_receta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id        BIGINT      NOT NULL REFERENCES receta (id),
    medicamento_id   BIGINT      NOT NULL REFERENCES medicamento (id),
    dosis            VARCHAR(50) NOT NULL,
    frecuencia       VARCHAR(50) NOT NULL,
    duracion_dias    INTEGER     NOT NULL,
    CONSTRAINT ck_item_receta_duracion CHECK (duracion_dias > 0)
);
CREATE INDEX ix_item_receta_receta ON item_receta (receta_id);

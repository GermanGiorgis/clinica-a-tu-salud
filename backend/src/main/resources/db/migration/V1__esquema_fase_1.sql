-- Fase 1: usuarios, catalogos, agenda y turnos.
-- Ver docs/modelo-datos.md para el modelo y las reglas de negocio.

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    rol           VARCHAR(20)  NOT NULL,
    nombre        VARCHAR(100) NOT NULL,
    apellido      VARCHAR(100) NOT NULL,
    telefono      VARCHAR(30),
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en     TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('PACIENTE', 'MEDICO', 'ASISTENTE', 'ADMIN'))
);
-- El email es unico sin distinguir mayusculas.
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(email));

CREATE TABLE paciente (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT      NOT NULL UNIQUE REFERENCES usuario (id),
    dni              VARCHAR(20) NOT NULL UNIQUE,
    fecha_nacimiento DATE        NOT NULL
);

CREATE TABLE medico (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL UNIQUE REFERENCES usuario (id),
    matricula  VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE especialidad (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE medico_especialidad (
    medico_id       BIGINT NOT NULL REFERENCES medico (id),
    especialidad_id BIGINT NOT NULL REFERENCES especialidad (id),
    PRIMARY KEY (medico_id, especialidad_id)
);
CREATE INDEX ix_medico_especialidad_especialidad ON medico_especialidad (especialidad_id);

CREATE TABLE consultorio (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL UNIQUE,
    ubicacion VARCHAR(150),
    piso      INTEGER
);

CREATE TABLE motivo_cancelacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE horario_atencion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id          BIGINT      NOT NULL REFERENCES medico (id),
    consultorio_id     BIGINT      NOT NULL REFERENCES consultorio (id),
    dia_semana         VARCHAR(10) NOT NULL,
    hora_inicio        TIME        NOT NULL,
    hora_fin           TIME        NOT NULL,
    duracion_turno_min INTEGER     NOT NULL,
    vigente_desde      DATE        NOT NULL,
    vigente_hasta      DATE,
    CONSTRAINT ck_horario_dia CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_horario_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_horario_duracion CHECK (duracion_turno_min BETWEEN 5 AND 240),
    CONSTRAINT ck_horario_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);
CREATE INDEX ix_horario_medico ON horario_atencion (medico_id, dia_semana);
CREATE INDEX ix_horario_consultorio ON horario_atencion (consultorio_id, dia_semana);

CREATE TABLE turno (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id           BIGINT       NOT NULL REFERENCES paciente (id),
    medico_id             BIGINT       NOT NULL REFERENCES medico (id),
    consultorio_id        BIGINT       NOT NULL REFERENCES consultorio (id),
    creado_por_id         BIGINT       NOT NULL REFERENCES usuario (id),
    motivo_cancelacion_id BIGINT       REFERENCES motivo_cancelacion (id),
    inicio                TIMESTAMP    NOT NULL,
    fin                   TIMESTAMP    NOT NULL,
    estado                VARCHAR(15)  NOT NULL,
    motivo_consulta       VARCHAR(500),
    creado_en             TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_turno_estado CHECK (estado IN
        ('RESERVADO', 'CONFIRMADO', 'ATENDIDO', 'AUSENTE', 'CANCELADO')),
    CONSTRAINT ck_turno_fin CHECK (fin > inicio),
    -- Regla 5: toda cancelacion lleva motivo, y solo las cancelaciones lo llevan.
    CONSTRAINT ck_turno_motivo_cancelacion CHECK
        ((estado = 'CANCELADO') = (motivo_cancelacion_id IS NOT NULL))
);

-- Regla 2: un medico no puede tener dos turnos activos en el mismo horario.
-- Lo garantiza la base de datos, asi dos reservas simultaneas no duplican el turno.
CREATE UNIQUE INDEX ux_turno_medico_inicio_activo
    ON turno (medico_id, inicio)
    WHERE estado <> 'CANCELADO';

CREATE INDEX ix_turno_medico_inicio ON turno (medico_id, inicio);
CREATE INDEX ix_turno_paciente_inicio ON turno (paciente_id, inicio);

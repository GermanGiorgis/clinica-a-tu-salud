-- Rol RECEPCIONISTA: atiende el mostrador (agenda de todos los medicos, reservas por DNI,
-- verificacion de identidad) pero NO accede a historias clinicas (ver docs/modelo-datos.md).
ALTER TABLE usuario DROP CONSTRAINT ck_usuario_rol;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_rol
    CHECK (rol IN ('PACIENTE', 'MEDICO', 'RECEPCIONISTA', 'ADMIN'));

-- Feriados y ausencias cargados por anticipado. Un rango de fechas inclusivo; si medico_id es NULL
-- vale para toda la clinica (feriado, cierre), si no, solo para ese medico (licencia, enfermedad).
-- Mientras exista, no se ofrecen ni se aceptan reservas esos dias.
CREATE TABLE dia_no_laborable (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desde       DATE         NOT NULL,
    hasta       DATE         NOT NULL,
    descripcion VARCHAR(150) NOT NULL,
    medico_id   BIGINT       REFERENCES medico (id),
    creado_por  BIGINT       NOT NULL REFERENCES usuario (id),
    creado_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_dia_no_laborable_rango CHECK (hasta >= desde),
    -- Un rango enorme no es un feriado: es un error de carga que bloquearia la agenda.
    CONSTRAINT ck_dia_no_laborable_largo CHECK (hasta - desde <= 365)
);

CREATE INDEX ix_dia_no_laborable_rango ON dia_no_laborable (desde, hasta);
CREATE INDEX ix_dia_no_laborable_medico ON dia_no_laborable (medico_id);

-- Fase 2b: cobertura (ver docs/modelo-datos.md). El paciente gestiona sus
-- propias afiliaciones; el turno puede, opcionalmente, asociarse a una de
-- ellas para saber con que cobertura se atendio.
CREATE TABLE obra_social (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100) NOT NULL,
    telefono VARCHAR(30)
);
CREATE UNIQUE INDEX ux_obra_social_nombre ON obra_social (lower(nombre));

CREATE TABLE afiliacion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id      BIGINT       NOT NULL REFERENCES paciente (id),
    obra_social_id   BIGINT       NOT NULL REFERENCES obra_social (id),
    numero_afiliado  VARCHAR(50)  NOT NULL,
    plan             VARCHAR(100),
    vigente_desde    DATE         NOT NULL,
    vigente_hasta    DATE,
    CONSTRAINT ck_afiliacion_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);
CREATE INDEX ix_afiliacion_paciente ON afiliacion (paciente_id);

ALTER TABLE turno ADD COLUMN afiliacion_id BIGINT REFERENCES afiliacion (id);

-- Derivacion por patologia (ver docs/modelo-datos.md): el paciente elige un
-- sintoma/patologia y el sistema lo traduce a una especialidad para filtrar
-- medicos. Es un catalogo que edita el admin, igual que Especialidad.
CREATE TABLE patologia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    especialidad_id BIGINT       NOT NULL REFERENCES especialidad (id)
);
CREATE UNIQUE INDEX ux_patologia_nombre ON patologia (lower(nombre));
CREATE INDEX ix_patologia_especialidad ON patologia (especialidad_id);

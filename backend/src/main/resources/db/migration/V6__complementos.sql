-- Fase 3: estudios complementarios, encuesta de satisfaccion y facturacion
-- simplificada (ver docs/modelo-datos.md).
CREATE TABLE estudio (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo   VARCHAR(50)  NOT NULL
);
CREATE UNIQUE INDEX ux_estudio_nombre ON estudio (lower(nombre));

CREATE TABLE orden_estudio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id  BIGINT       NOT NULL REFERENCES consulta (id),
    estudio_id   BIGINT       NOT NULL REFERENCES estudio (id),
    estado       VARCHAR(15)  NOT NULL,
    indicaciones VARCHAR(500),
    emitida_en   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_orden_estudio_estado CHECK (estado IN ('SOLICITADA', 'COMPLETADA'))
);
CREATE INDEX ix_orden_estudio_consulta ON orden_estudio (consulta_id);

CREATE TABLE resultado_estudio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_estudio_id BIGINT   NOT NULL UNIQUE REFERENCES orden_estudio (id),
    resultado       TEXT      NOT NULL,
    cargado_en      TIMESTAMP NOT NULL DEFAULT now()
);

-- Regla: una encuesta por turno, solo para un turno ya atendido (lo valida el servicio).
CREATE TABLE encuesta (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id  BIGINT      NOT NULL UNIQUE REFERENCES turno (id),
    puntaje   INTEGER     NOT NULL,
    comentario VARCHAR(500),
    creada_en TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_encuesta_puntaje CHECK (puntaje BETWEEN 1 AND 5)
);

-- Facturacion simplificada: una factura por turno, con sus items.
CREATE TABLE factura (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id    BIGINT        NOT NULL UNIQUE REFERENCES turno (id),
    total       DECIMAL(12,2) NOT NULL,
    medio_pago  VARCHAR(20)   NOT NULL,
    emitida_en  TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_factura_medio_pago CHECK
        (medio_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'OBRA_SOCIAL')),
    CONSTRAINT ck_factura_total CHECK (total >= 0)
);

CREATE TABLE item_factura (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id  BIGINT        NOT NULL REFERENCES factura (id),
    descripcion VARCHAR(200)  NOT NULL,
    importe     DECIMAL(12,2) NOT NULL,
    CONSTRAINT ck_item_factura_importe CHECK (importe >= 0)
);
CREATE INDEX ix_item_factura_factura ON item_factura (factura_id);
